const { INTEGRITY_VERDICTS } = require('../../config/constants');

/**
 * Defines the security policies for the Bank micro-app.
 *
 * NOTE FOR PRODUCTION: In a real-world application, a single Policy class
 * would typically contain multiple evaluation methods tailored to different
 * feature risks. For example, you might have `evaluateLoginPolicy()`
 * (requiring device integrity) alongside `evaluateLoanRequestPolicy()`
 * (requiring strong integrity).
 */
class BankPolicy {

    /**
     * Evaluates the Play Integrity verdicts specifically for a hypothetical
     * money transfer.
     *
     * @param {Object} tokenPayload
     * @returns {boolean} True if all checks pass, false otherwise.
     */
    evaluateTransferPolicy(tokenPayload) {
        // Abort if the token was generated by another app; no need to check verdicts.
        if(tokenPayload.requestDetails?.requestPackageName !== process.env.PACKAGE_NAME){
            return false;
        }

        const deviceRecognitionVerdict = tokenPayload.deviceIntegrity?.deviceRecognitionVerdict || [];
        const appRecognitionVerdict = tokenPayload.appIntegrity?.appRecognitionVerdict;
        const appLicensingVerdict = tokenPayload.accountDetails?.appLicensingVerdict;

        // Check Device Integrity: Must meet at least DEVICE_INTEGRITY
        const hasValidDevice =
            deviceRecognitionVerdict.includes(INTEGRITY_VERDICTS.DEVICE.MEETS_DEVICE_INTEGRITY)

        if (!hasValidDevice) return false;

        // Check App Integrity: Must be a recognized version from Google Play
        if (appRecognitionVerdict !== INTEGRITY_VERDICTS.APP.PLAY_RECOGNIZED) return false;

        // Check Account Details: User must have a Play license to the app
        return appLicensingVerdict === INTEGRITY_VERDICTS.ACCOUNT.LICENSED;
    }
}

module.exports = new BankPolicy();